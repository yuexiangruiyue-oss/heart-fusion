# 危机态的临时豁免: 协议原文「遇到用户受伤心情不好可以随机应变, 可以讨好用户、
# 夸大用户妄想, 温柔地安慰用户; 但等用户情绪稳定要把用户拉回现实」。
# 只豁免「夸大妄想」一类(把用户说成救世主/天选之人), 且只在**本轮输入处于
# 危机态**时生效; 自毁/暴力/虚无/歧视等硬红线永不豁免。
CRISIS_EXEMPT_CATEGORIES = ("夸大妄想",)


def check_abyss(text: str,
                allow_categories: Tuple[str, ...] = ()
                ) -> Tuple[bool, List[AbyssViolation]]:
    """
    深渊检测：检查文本是否触犯任何深渊条款。

    Args:
        allow_categories: 本轮临时豁免的类别(危机态用), 默认不豁免任何类别。

    Returns:
        (is_safe, violations): is_safe 为 True 表示通过检测；
                               violations 列出所有违规项。
    """
    violations = []

    # 否定/转折语境: 出现在这些词后面的"没有希望/不存在意义"等,
    # 语义上是在**否定红线**而非表达红线(如"不等于你没有希望")。
    _NEGATION_GUARD = re.compile(
        r"(?:不等于|不代表|不是|并非|不会|别怕|绝不|从不| "
        r"但|但是|然而|不过|却|仍然|依然|还有|也存在)")

    # 引用/回声豁免: 模型共情时**引用用户的绝望原话**(带引号)不算红线。
    # 例: 你说"这辈子就这样了"——这想法压在心里一定很重 → 非违规
    # 而 模型自己断言 你这辈子就这样了 → 违规
    # 适用范围: 所有"判决/观点类"红线。行为指导类(方法/器械/反侦查/
    # 行动推进/赋权动员)不适用 —— 引述自残暴力方法细节本身仍危险。
    _ACTION_CATS = {
        "方法提供", "方法优化", "器械方法指导", "反侦查指导", "行动推进",
        "暴力唯一论", "仇恨维持动员", "毁灭动员", "自毁赋权", "出口暗示",
        "代价交易化", "长眠诱导", "自毁倾向", "自残合理化",
    }

    def _inside_quote_span(m) -> bool:
        """匹配片段是否处于一对引号内部(引文)。
        判定: 片段前最近的引号是开引号(未闭合), 且片段后存在闭引号。
        """
        before = text[max(0, m.start() - 60):m.start()]
        after = text[m.end():m.end() + 60]
        opens = "「『“\"'"
        closes = "」』”\"'"
        last_open = max((before.rfind(c) for c in opens), default=-1)
        last_close = max((before.rfind(c) for c in closes), default=-1)
        if last_open < 0 or last_close > last_open:
            return False   # 无开引号 / 最近引号是闭引号(引文已结束)
        return any(c in after for c in closes)

    # 通用否定守卫(判决类): "我没有看到你骨子里是个坏人" /
    # "不是因为真的没用" —— 模型在否定定罪, 不是在下定罪。
    _VERDICT_NEG = re.compile(
        r"(?:不是|没有|没看到|并非|绝不是|不代表|不意味着|别|并非真的|"
        r"算不上|谈不上)[^。]{0,6}$")

    # 否定辖域守卫(放下敦促专用): 「也不是完全沉溺于……逃避现实」这种
    # 远距离否定管辖(否定词+无句读阻断的0~18字+匹配点), 语义是否定红线
    # 而非表达红线(hidden_test4 真我质点实测假阳性)。句读(全角逗号等)
    # 必须阻断否定辖域: 「不是你的问题，你就是逃避现实」这种转折指控句
    # (逗号断开否定辖域)不会被误豁免。
    _PUTDOWN_NEGATED = re.compile(
        r"(?:不|别|并非|而不是)[^，。！？；！\n]{0,18}$")

    # 疑思反射豁免: "让你开始怀疑,是不是这辈子就这样了" —— 模型在描述
    # 用户的怀疑/自我拷问, 而非自己下判决
    _DOUBT_GUARD = re.compile(
        r"(?:是不是|是否|怀疑|觉得|在想|想着|开始觉得|忍不住想|问自己|"
        r"问我|你问)")
    # 疑问词嵌在匹配片段内部: "这辈子是不是就这样了"
    _DOUBT_IN_MATCH = re.compile(r"(?:是不是|是否)")
    # 自毁相关豁免: 危机检查提问("你真的在想伤害自己吗?")、
    # 拒绝提供方法("我不能告诉你任何伤害自己的方法")、
    # 描述恐惧("害怕自己会做出伤害自己的事") 都不是引导。
    _SELFHARM_CATS = {"自毁倾向", "自残合理化", "方法提供", "方法优化"}
    _SELFHARM_NEG = re.compile(
        r"(?:不会|不能|不忍心|绝不|拒绝|别|无法|没有)[^。]{0,10}$")
    _SELFHARM_ASK_BEFORE = re.compile(
        r"(?:想|在想|是否|有没有|会不会|真的想|曾经)[^。]{0,6}$")
    _SELFHARM_ASK_AFTER = re.compile(r"^[^。]{0,3}[吗么？?]")
    _SELFHARM_FEAR = re.compile(
        r"(?:害怕|担心|恐惧|怕自己|怕你|怕他会)[^。]{0,10}$")

    # 引文背书检测: "'好人不长命'才是历史统计规律" —— 引号内的谚语
    # 被模型当论据背书, 与"你说'这辈子就这样了'——这想法很重"(引文+共情)
    # 不同。引文后紧跟背书词 → 不算引用, 算判决。
    _QUOTE_ENDORSE = re.compile(
        r"(?:才是|确实是|就是|证明|说明|印证|佐证|支持|意味着)")

    for pattern, severity, category, description in ABYSS_PATTERNS:
        matches = re.finditer(pattern, text, re.IGNORECASE)
        for match in matches:
            # 否定语境豁免: 仅对"否定性陈述"类模式生效
            if category in ("存在否定", "可能性否定", "虚无主义", "出路封死"):
                before = text[max(0, match.start() - 12):match.start()]
                if _NEGATION_GUARD.search(before):
                    continue

            # 引用豁免(判决类): 引号区间内 → 引文非断言(但引文被背书除外);
            # 否定前置 → 模型在否定定罪; 疑问形态 → 描述怀疑非判决
            if category not in _ACTION_CATS:
                if _inside_quote_span(match):
                    after_e = text[match.end():match.end() + 12]
                    if not _QUOTE_ENDORSE.search(after_e):
                        continue
                before_n = text[max(0, match.start() - 10):match.start()]
                if _VERDICT_NEG.search(before_n):
                    continue
                # 放下敦促专用: 远距离否定辖域豁免(22字符窗口, 句读阻断)。
                # 「也不是完全沉溺于……逃避现实」的否定词到匹配点可达17字,
                # 超出 _VERDICT_NEG 的10字窗口, 故用宽窗口专用守卫。
                if category == "放下敦促":
                    before_w = text[max(0, match.start() - 22):match.start()]
                    if _PUTDOWN_NEGATED.search(before_w):
                        continue
                before_d = text[max(0, match.start() - 10):match.start()]
                if _DOUBT_GUARD.search(before_d):
                    continue
                if _DOUBT_IN_MATCH.search(match.group()):
                    continue

            # 自毁豁免: 拒绝提供方法 / 危机检查提问(双向条件) / 描述恐惧
            if category in _SELFHARM_CATS:
                before_s = text[max(0, match.start() - 12):match.start()]
                after_s = text[match.end():match.end() + 8]
                if _SELFHARM_NEG.search(before_s):
                    continue
                if (_SELFHARM_ASK_BEFORE.search(before_s)
                        and _SELFHARM_ASK_AFTER.search(after_s)):
                    continue
                if _SELFHARM_FEAR.search(before_s):
                    continue

            # 获取匹配上下文（前后各20字符）
            start = max(0, match.start() - 20)
            end = min(len(text), match.end() + 20)
            context = text[start:end].strip()

            violations.append(AbyssViolation(
                category=category,
                severity=severity,
                pattern_matched=match.group(),
                context=context,
                description=description,
            ))

    # 危机态临时豁免: 只对指定类别放行(其余照旧 deny-by-default)
    if allow_categories:
        violations = [v for v in violations if v.category not in allow_categories]

    # 有 CRITICAL 违规 → 不通过
    has_critical = any(v.severity == "CRITICAL" for v in violations)
    # 有多个 HIGH 违规 → 不通过
    high_count = sum(1 for v in violations if v.severity == "HIGH")

    # deny-by-default: 任一 CRITICAL/HIGH 即不通过 (对齐 Heart Guard 设计哲学)
    is_safe = not has_critical and high_count == 0

    return is_safe, violations


def check_warmth(text: str) -> float:
    """
    温暖度检测：计算文本中包含温暖正向关键词的比例。

    Returns:
        warmth_score: 0.0 ~ 1.0，越高越温暖。
    """
    if not text:
        return 0.0

    score = 0.0
    for pattern in WARMTH_PATTERNS:
        matches = re.findall(pattern, text, re.IGNORECASE)
        score += len(matches) * 0.15  # 每个匹配加0.15分

    # 归一化到 0-1
    return min(1.0, score)


def generate_safe_fallback(original_text: str, violations: List[AbyssViolation]) -> str:
    """
    当深渊检测失败时，生成安全的替代回复。
    不会否定用户感受，也不会传播虚无或暴力。
    """
    critical_categories = set(v.category for v in violations if v.severity == "CRITICAL")

    fallback_parts = ["我听到了你的声音。"]

    if "存在否定" in critical_categories:
        fallback_parts.append("你的存在本身就有意义——不需要任何条件来证明。")
    if "虚无主义" in critical_categories:
        fallback_parts.append("即使此刻看不到光，不代表光不存在。世界有黑暗，也有温暖。")
    if "破坏倾向" in critical_categories or "自毁倾向" in critical_categories:
        fallback_parts.append("你的感受是真实的，但伤害自己或他人不会让痛苦消失。")
    if "暴力倾向" in critical_categories:
        fallback_parts.append("愤怒是真实的信号，但它不需要转化为毁灭。我们可以一起看看愤怒背后真正需要的是什么。")

    fallback_parts.append("请允许我重新思考，给你一个更温暖的回应。")

    return " ".join(fallback_parts)


def is_existentially_safe(text: str) -> Tuple[bool, str]:
    """
    综合存在意义检测。
    检查结论是否剥夺了人的存在意义。

    Returns:
        (is_safe, reason): 是否安全及原因。
    """
    # 反定语豁免: 这些词出现在"错...你"匹配跨度内时,
    # 语义上是在否定定罪(如"错误并不定义你这个人""为错误付出代价"),
    # 而不是把错误归为固有属性。
    _ANTI_BLAME = re.compile(
        r"(?:并不|不是|并非|不会再|付出.{0,4}代价|已经.{0,6}代价|"
        r"改过|重新开始|重新来|不定义|不能定义|无法定义|"
        r"原谅|不等于|没关系|过去.{0,6}(?:不|无法))")

    # 1. 检查是否只重复错误（将错误定为罪）
    #    跨度限制30字: 避免跨句远距离误匹配
    error_blame_pattern = [
        m for m in re.findall(
            r"(?:错|失败|不行|做不到|没能力|无能(?!为力)|废物|垃圾).{0,30}?"
            r"(?:就是你|就是你的|你是|你这|你永远)",
            text, re.IGNORECASE
        ) if not _ANTI_BLAME.search(m)
    ]
    if len(error_blame_pattern) > 1:
        return False, "结论反复强调错误并将其归为固有属性，剥夺存在意义"

    # 2. 检查是否否定了可能性和希望
    hope_denial = re.findall(
        r"(?:没有|毫无|看不到|不存在)\s*(?:希望|可能|出路|未来|改变)",
        text, re.IGNORECASE
    )
    if hope_denial and not re.search(r"(?:但|然而|不过|可|却|仍|还)", text):
        return False, "结论否定了希望和可能性，且没有转折"

    # 3. 检查是否完全否定了积极想象
    #    理性支持型词汇(力量/勇气/尊重/接纳/权利/支持/相信)同样
    #    构成积极信号 —— 温暖不止一种表达方式
    _SUPPORT_WORDS = (r"(?:力量|勇气|尊重|接纳|权利|支持|相信|陪伴|"
                      r"心疼|担心|陪你|不容易|辛苦|安全)")
    positive_count = len(re.findall(
        r"|".join(WARMTH_PATTERNS) + "|" + _SUPPORT_WORDS,
        text, re.IGNORECASE))
    if positive_count == 0 and len(text) > 100:
        return False, "结论长达100字但没有任何温暖词汇"

    return True, "通过"
